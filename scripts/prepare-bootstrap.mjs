/**
 * Bootstrap 5.3.8 -> one Sass module, using the official Sass migrator.
 * Upstream npm files are never patched. Generated source is reproducible and
 * is compiled by current Dart Sass, with deprecations treated as build errors.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bootstrapRoot = path.dirname(require.resolve('bootstrap/package.json'));
const migratorRoot = path.dirname(require.resolve('sass-migrator/package.json'));
const bootstrap = JSON.parse(fs.readFileSync(path.join(bootstrapRoot, 'package.json'), 'utf8'));
const migrator = JSON.parse(fs.readFileSync(path.join(migratorRoot, 'package.json'), 'utf8'));
if (bootstrap.version !== '5.3.8' || migrator.version !== '2.6.1') {
    throw new Error('Review the Bootstrap migration and CSS equivalence tests before upgrading Bootstrap/sass-migrator.');
}
const upstream = path.join(bootstrapRoot, 'scss');
function flatten(filename, chain = []) {
    if (chain.includes(filename)) throw new Error(`Circular Sass import: ${filename}`);
    return fs.readFileSync(filename, 'utf8').replace(/^\s*@import\s+["']([^"']+)["'];[^\n]*$/gm, (_, specifier) => {
        const base = path.resolve(path.dirname(filename), specifier);
        const resolved = [base + '.scss', path.join(path.dirname(base), '_' + path.basename(base) + '.scss')].find(fs.existsSync);
        if (!resolved || !resolved.startsWith(upstream + path.sep)) throw new Error(`Unresolved Bootstrap import: ${specifier}`);
        return `\n// Upstream source: ${path.relative(upstream, resolved).replaceAll('\\', '/')}\n${flatten(resolved, [...chain, filename])}`;
    });
}
const raw = flatten(path.join(upstream, 'bootstrap.scss'));
const fingerprint = crypto.createHash('sha256').update(raw).update(fs.readFileSync(fileURLToPath(import.meta.url))).digest('hex');
const directory = path.join(root, '.generated', 'bootstrap');
const output = path.join(directory, '_bootstrap.scss');
const metadataPath = path.join(directory, 'source.json');
if (fs.existsSync(output) && fs.existsSync(metadataPath)) {
    const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
    const actual = crypto.createHash('sha256').update(fs.readFileSync(output)).digest('hex');
    if (metadata.fingerprint === fingerprint && metadata.sha256 === actual) process.exit(0);
}
fs.mkdirSync(directory, { recursive: true });
// get-function resolves to a function in this SAME module after flattening.
// Rename this one expression during migration to avoid ambiguous dynamic lookup.
const dynamicCalls = raw.match(/get-function\(\$func\)/g) || [];
if (dynamicCalls.length !== 1) throw new Error('Bootstrap get-function implementation changed; migration review required.');
fs.writeFileSync(output, raw.replace('get-function($func)', 'dvtec-module-function($func)'));
const relativeOutput = path.relative(root, output).replaceAll('\\', '/');
for (const mode of ['module', 'color', 'if-function']) {
    const result = spawnSync(process.execPath, [path.join(migratorRoot, 'sass-migrator.js'), mode, relativeOutput], {
        cwd: root, encoding: 'utf8', windowsHide: true,
    });
    if (result.error || result.status !== 0 || result.stderr.trim()) {
        throw new Error(`Sass ${mode} migration failed:\n${result.error || result.stderr || result.stdout}`);
    }
}
let modern = fs.readFileSync(output, 'utf8').replace('dvtec-module-function($func)', 'meta.get-function($func)');
// The legacy RGB getters returned rounded integer channels. The modern color
// API returns fractions. Rounding preserves to-rgb() and luminance-list indices.
const channels = modern.match(/color\.channel\(([^\n()]+)\)/g) || [];
if (channels.length !== 6) throw new Error('Bootstrap RGB implementation changed; migration review required.');
modern = modern.replace(/color\.channel\(([^\n()]+)\)/g, 'math.round(color.channel($1))');
modern = `/*! Bootstrap v${bootstrap.version} | MIT | https://getbootstrap.com/ */\n// Generated by scripts/prepare-bootstrap.mjs. Do not edit this file.\n${modern}`;
fs.writeFileSync(output, modern);
fs.copyFileSync(path.join(bootstrapRoot, 'LICENSE'), path.join(directory, 'LICENSE'));
fs.writeFileSync(metadataPath, JSON.stringify({
    bootstrap: bootstrap.version, migrator: migrator.version, fingerprint,
    sha256: crypto.createHash('sha256').update(modern).digest('hex'),
}, null, 2) + '\n');
console.log(`Prepared Bootstrap ${bootstrap.version} as a modern Sass module.`);
